def esc(text):
    """Escape a data value (a name taken from the tools' DATA) for HTML."""
    return html.escape(str(text), quote=True)


def svg_data_url(path):
    """An SVG file as a compact data: URL for CSS: whitespace collapsed, double
    quotes turned into single ones (when the file has none), and only the
    characters a URL cannot carry, or that would end the CSS string or the HTML
    attribute, percent-encoded (%, #, <, >, &, double quote, braces, controls
    and anything outside ASCII). Gzip packs this almost as well as the file."""
    with open(path, encoding="utf-8") as fh:
        s = re.sub(r"\s+", " ", fh.read().strip()).replace("> <", "><")
    if "'" not in s:
        s = s.replace('"', "'")
    return "data:image/svg+xml," + "".join(
        quote(ch, safe="") if ch in '%#<>&"{}|\\^`[]' or not " " <= ch <= "~" else ch
        for ch in s)


def group_code(d, group):
    """'Group 2A', '2A 类', 'groupe 2A' ... from the language's lbl_grp pattern."""
    return d["lbl_grp"].replace("{g}", group)


def vol_text(d, volume, year):
    """'Vol. 100C, 2009' or 'Suppl. 7, 1987' in the page's language."""
    m = re.match(r"^Sup\s*(\S+)$", volume)
    pattern = d["work_sup"] if m else d["work_vol"]
    return pattern.replace("{n}", m.group(1) if m else volume).replace("{year}", str(year))


def mailto_report(d, lang):
    """mailto: URL for a correction, its body the four lines of the form.

    RFC 6068 wants CRLF line breaks in a mailto body. The result goes into an
    href attribute, so its one '&' is written as &amp;."""
    lines = [html.unescape(re.sub(r"<[^>]+>", "", d[key])).strip() + COLON.get(lang, ": ")
             for key in REPORT_FIELDS]
    body = "\r\n".join(lines) + "\r\n"
    return "mailto:%s?subject=%s&amp;body=%s" % (REPORT_TO, quote(REPORT_SUBJECT),
                                                 quote(body, safe=""))


def swatch(cls):
    """The small square in the tools' colour for a group (g1 ...) or a grade
    (strong ...); site.css .sw.<cls>. The label next to it carries the meaning."""
    return '<span class="sw %s" aria-hidden="true"></span>' % cls


def render_work(work, d, lang):
    """work.html: the sector index and one table per sector, from data/work.json."""
    sep = LIST_SEP.get(lang, ", ")
    toc, sections = [], []
    for sector in work["sectors"]:
        sid, n = sector["id"], len(sector["agents"])
        name = d["work_sec_" + sid]
        toc.append('<li><a href="#%s">%s <span class="n">%d</span></a></li>' % (sid, name, n))
        rows = []
        for a in sector["agents"]:
            g = a["group"]
            counts = []
            for kind in ("established", "suspected"):
                names = sep.join(esc(c["name"][lang]) for c in a[kind])
                counts.append('<td><span class="n">%d</span>%s</td>'
                              % (len(a[kind]), " " + names if names else ""))
            rows.append('<tr><th scope="row"><a href="%s">%s</a></th>'
                        '<td>%s%s <span class="gc">%s</span></td>%s<td class="ev">%s</td></tr>'
                        % (esc(tool_link("cancer", "exposure", a["id"], lang)), esc(a["name"][lang]),
                           swatch(GROUP_KEY[g].replace("lbl_", "")), d[GROUP_KEY[g]], group_code(d, g),
                           "".join(counts), vol_text(d, a["volume"], a["year"])))
        sections.append(
            '<section class="work-sec" id="%s">\n<h2 id="h-%s">%s <span class="n">%d</span></h2>\n'
            '<div class="tbl-wrap" role="region" tabindex="0" aria-labelledby="h-%s">\n'
            '<table class="work-table">\n<colgroup><col class="c-agent"><col class="c-label">'
            '<col class="c-est"><col class="c-sus"><col class="c-ev"></colgroup>\n'
            '<thead><tr><th scope="col">%s</th><th scope="col">%s</th><th scope="col">%s</th>'
            '<th scope="col">%s</th><th scope="col">%s</th></tr></thead>\n<tbody>\n%s\n</tbody>\n'
            '</table>\n</div>\n</section>'
            % (sid, sid, name, n, sid, d["work_th_agent"], d["work_th_label"], d["work_th_est"],
               d["work_th_sus"], d["work_th_eval"], "\n".join(rows)))
    return '<ul>%s</ul>' % "".join(toc), "\n\n".join(sections)


