def _git(*args):
    return subprocess.run(["git"] + list(args), cwd=HERE, capture_output=True,
                          text=True, check=True).stdout


def dirty_paths():
    """Paths that differ from the last commit (edited, new or just rebuilt).
    None when there is no git checkout: then every page is dated today."""
    try:
        out = _git("status", "--porcelain", "-z", "--untracked-files=all")
    except (OSError, subprocess.CalledProcessError):
        return None
    paths, entries, i = set(), out.split("\0"), 0
    while i < len(entries):
        e = entries[i]
        if len(e) > 3:
            paths.add(e[3:])
            if e[0] in "RC":      # a rename names the old path next; skip it
                i += 1
        i += 1
    return paths


def lastmod(path, dirty):
    """Date of a page for <lastmod>: the day of the last commit that touched its
    file (or game folder), git log -1 --format=%cs, which needs the full history
    (rebuild.yml checks out with fetch-depth: 0). A page that differs from that
    commit, because it was edited or this build has just rewritten it, is dated
    today: it becomes the commit of today once pushed, so a build run on the day
    of the commit, here or in the Rebuild Action, writes the same sitemap."""
    if dirty is None:
        return date.today().isoformat()
    folder = path.endswith("/")
    if any(p == path or (folder and p.startswith(path)) for p in dirty):
        return date.today().isoformat()
    try:
        day = _git("log", "-1", "--format=%cs", "--", path).strip()
    except (OSError, subprocess.CalledProcessError):
        day = ""
    return day or date.today().isoformat()


def write_sitemap():
    """One <url> per page per language, each with its <lastmod> and every
    language as an alternate. Search engines want the alternates repeated inside
    every entry, not only on the page that happens to be canonical."""
    dirty = dirty_paths()
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"'
           ' xmlns:xhtml="http://www.w3.org/1999/xhtml">']

    def entry(loc, day, alternates):
        out.append("  <url>")
        out.append("    <loc>%s</loc>" % html.escape(loc))
        out.append("    <lastmod>%s</lastmod>" % day)
        if len(alternates) > 1:
            for other, href in alternates.items():
                out.append('    <xhtml:link rel="alternate" hreflang="%s" href="%s"/>'
                           % (other, html.escape(href)))
            out.append('    <xhtml:link rel="alternate" hreflang="x-default" href="%s"/>'
                       % html.escape(alternates["en"]))
        out.append("  </url>")

    for page in PAGES:
        alternates = {l: abs_url(l, page) for l in LANGS}
        for lang in LANGS:
            path = page if lang == "en" else "%s/%s" % (lang, page)
            entry(alternates[lang], lastmod(path, dirty), alternates)
    # The two tools stay out of the sitemap (decision 1: noindex while in preview).
    for path, alternates in STATIC_PAGES:
        day = lastmod(path, dirty)
        for lang, loc in alternates.items():
            entry(loc, day, alternates)
    out.append("</urlset>")
    with open(os.path.join(HERE, "sitemap.xml"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")


def write_robots():
    """GitHub Pages serves the whole repository, so robots.txt asks crawlers to
    leave the build inputs and internal files alone: the search index, the
    templates, the 2026-09-20 review, the scripts, the translations and data."""
    lines = ["User-agent: *", "Allow: /",
             "Disallow: /assets/search/", "Disallow: /templates/", "Disallow: /editorial-2026-09-20/",
             "Disallow: /scripts/", "Disallow: /i18n/", "Disallow: /data/",
             "", "Sitemap: %s/sitemap.xml" % SITE_URL]
    with open(os.path.join(HERE, "robots.txt"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


def main():
    data = {l: load(l) for l in LANGS}

    # --- key parity: a missing key must fail the build, not silently ship English
    base = set(data["en"])
    problems = []
    for l in LANGS[1:]:
        missing = base - set(data[l])
        extra = set(data[l]) - base
        if missing:
            problems.append("%s missing %d: %s" % (l, len(missing), sorted(missing)[:6]))
        if extra:
            problems.append("%s has %d unknown: %s" % (l, len(extra), sorted(extra)[:6]))
        empty = [k for k, v in data[l].items() if not str(v).strip()]
        if empty:
            problems.append("%s empty values: %s" % (l, empty[:6]))
    if problems:
        raise SystemExit("Translation key problems:\n  " + "\n  ".join(problems))

    for page in PAGES:
        if page not in OG_IMAGES:
            raise SystemExit("%s has no share image in OG_IMAGES" % page)
        for lang in LANGS:
            f = OG_IMAGES[page]["file"].replace("{lang}", lang)
            if not os.path.exists(os.path.join(HERE, "assets", "og", f)):
                raise SystemExit("share image assets/og/%s is missing" % f)

    templates = {}
    for page in PAGES:
        with open(os.path.join(TPL, page), encoding="utf-8") as fh:
            templates[page] = fh.read()

    # work.html renders the committed output of scripts/build_work_data.py
    with open(WORK_JSON, encoding="utf-8") as fh:
        work = json.load(fh)

    # same picture in every language (see CHRONIC_NET_SVG)
    thumb_chronic = "background-image:url(&quot;%s&quot;)" % svg_data_url(CHRONIC_NET_SVG)

    written = []
    for lang in LANGS:
        d = data[lang]
        outdir = HERE if lang == "en" else os.path.join(HERE, lang)
        os.makedirs(outdir, exist_ok=True)

        work_toc, work_sectors = render_work(work, d, lang)
        shared = {
            "URL_HWC": url(lang, "how-we-check.html", lang),
            "URL_WORK": url(lang, "work.html", lang),
            "MAILTO_REPORT": mailto_report(d, lang),
            "WORK_TOC": work_toc,
            "WORK_SECTORS": work_sectors,
            "WORK_REC9": render_rec9(work, d, lang),
            "WORK_CHRONIC": render_work_chronic(work, d, lang),
        }
        for key, (tool, kind, id_) in TOOL_DEEP.items():
            shared[key] = esc(tool_link(tool, kind, id_, lang))
        # the three example chips of the search box are links for readers
        # without JavaScript: their word goes into a URL, percent-encoded
        for i in (1, 2, 3):
            shared["Q_EX%d" % i] = quote(plain(d["search_ex%d" % i]), safe="")
        shared["JSONLD_HOME"] = jsonld_home(d, lang)
        shared["THUMB_CHRONIC_BG"] = thumb_chronic
        for g in GROUP_KEY:
            shared["GRP_" + g] = group_code(d, g)

        for page in PAGES:
            # language switcher: plain links, no JavaScript required. Built per
            # page so switching language keeps you on the same page rather than
            # dumping you back to the home page.
            switch = []
            for other in LANGS:
                label = data[other]["lang_name"]
                if other == lang:
                    switch.append('<span class="lang-cur" aria-current="true">%s</span>' % label)
                else:
                    switch.append('<a href="%s" hreflang="%s">%s</a>'
                                  % (url(other, page, lang), other, label))
            switch_html = "".join(switch)

            # hreflang alternates for this page across every language
            alts = ['<link rel="alternate" hreflang="%s" href="%s">'
                    % (o, abs_url(o, page)) for o in LANGS]
            alts.append('<link rel="alternate" hreflang="x-default" href="%s">'
                        % abs_url("en", page))

            ctx = dict(d)
            ctx["LANG"] = lang
            ctx["DIR"] = d.get("lang_dir", "ltr")
            ctx["PREFIX"] = "" if lang == "en" else "../"
            ctx["URL_HOME"] = url(lang, "index.html", lang)
            ctx["URL_EXPLORER"] = url(lang, "explorer.html", lang)
            ctx["URL_ABOUT"] = url(lang, "about.html", lang)
            ctx["URL_GAMES"] = url(lang, "games.html", lang)
            ctx["URL_READING"] = url(lang, "reading.html", lang)
            ctx["URL_GAME1"] = ctx["PREFIX"] + GAME1_PATH
            ctx["URL_GAME2"] = ctx["PREFIX"] + GAME2_PATH
            ctx["URL_GAME3"] = ctx["PREFIX"] + GAME3_PATH
            ctx["URL_TOOL"] = tool_link("cancer", None, None, lang)
            ctx["URL_TOOL2"] = tool_link("chronic", None, None, lang)
            # the Code page localises itself client-side; hand it the language
            ctx["URL_PREVENTION"] = (ctx["PREFIX"] + PREVENTION_PATH
                                     + ("" if lang == "en" else "?lang=" + lang))
            # the timeline speaks en/zh; only zh gets the handoff
            ctx["URL_TIMELINE"] = (ctx["PREFIX"] + "timeline/"
                                   + ("?lang=zh" if lang == "zh" else ""))
            ctx["URL_NOTE1"] = NOTE1_URL
            ctx["CANONICAL"] = abs_url(lang, page)
            og = OG_IMAGES[page]
            ctx["OG_IMAGE"] = OG_BASE + og["file"].replace("{lang}", lang)
            ctx["OG_IMAGE_ALT"] = esc(og["alt"][lang])
            ctx["OG_IMAGE_W"], ctx["OG_IMAGE_H"], ctx["OG_IMAGE_TYPE"] = OG_W, OG_H, OG_TYPE
            ctx["OG_LOCALE"] = OG_LOCALE[lang]
            ctx["LANGSWITCH"] = switch_html
            ctx["HREFLANG"] = "\n".join(alts)
            ctx.update(shared)

            missing = []

            def sub(m):
                k = m.group(1)
                if k not in ctx:
                    missing.append(k)
                    return m.group(0)
                return str(ctx[k])

            html = PLACEHOLDER.sub(sub, templates[page])
            # dev-notes stay in the templates; the shipped page carries none
            html = re.sub(r"[ \t]*<!--(?!\[).*?-->\n?", "", html, flags=re.S)
            if missing:
                raise SystemExit("%s/%s: unresolved placeholders %s"
                                 % (lang, page, sorted(set(missing))))

            path = os.path.join(outdir, page)
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(html)
            written.append(os.path.relpath(path, HERE))

    write_sitemap()
    write_robots()

    print("Built %d pages across %d languages:" % (len(written), len(LANGS)))
    for w in written:
        print("   ", w)
    print("\nKey count: %d strings x %d languages" % (len(base), len(LANGS)))

    # The About citation (cite_p) and the How we check versions (hwc_ver_c) name
    # the cancer tool's build date by a literal {cancerBuilt}; the publisher fills
    # it in (with the date of the tool's DATA.meta.built) before the pages go
    # live. Say so while any is open.
    pending = sorted({"%s:%s" % (l, k) for l in LANGS for k, v in data[l].items()
                      if "{cancerBuilt}" in str(v)})
    if pending:
        print("NOTE: the placeholder {cancerBuilt} is still open in %s: replace it"
              " with the cancer tool's build date before publishing." % ", ".join(pending))


if __name__ == "__main__":
    main()
