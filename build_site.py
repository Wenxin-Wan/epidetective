def load(lang):
    with open(os.path.join(I18N, "%s.json" % lang), encoding="utf-8") as fh:
        return json.load(fh)


def url(lang, page, from_lang):
    """Relative URL to `page` in `lang`, seen from a page in `from_lang`.

    Links within the same language must stay bare filenames. Emitting
    "../zh/index.html" from inside zh/ resolves to the same file, but the
    browser treats it as a different URL and reloads the whole page, so
    in-page anchors stop working.
    """
    if lang == from_lang:
        return page
    prefix = "" if from_lang == "en" else "../"
    sub = "" if lang == "en" else lang + "/"
    return prefix + sub + page


def abs_url(lang, page):
    """Canonical absolute URL for `page` in `lang`.

    canonical, og:url, hreflang and the sitemap all need absolute URLs -- search
    engines treat a relative hreflang as a weaker hint, and social scrapers
    cannot resolve a relative og:url at all. index.html is dropped so the
    canonical form is the directory, matching what the server actually serves.
    """
    sub = "" if lang == "en" else lang + "/"
    leaf = "" if page == "index.html" else page
    return "%s/%s%s" % (SITE_URL, sub, leaf)


def tool_link(tool, kind, id, lang):
    """Absolute URL into one of the two tools, in the reader's language.

    tool  "cancer" or "chronic"
    kind  None for the tool's front door, else one of TOOL_KINDS[tool]
    id    the id exactly as the tool's DATA writes it ("Aspartame", "Tobacco
          smoking", "high_sbp"). For kind "link" either "risk|disease" or a
          (risk, disease) pair. Ignored for "map"; the section id for "anchor".
    lang  one of LANGS; always written, English included

    Examples:
      tool_link("cancer", "exposure", "Aspartame", "fr")
        -> https://tools.epidetective.com/cancer/?lang=fr#exposure=Aspartame
      tool_link("chronic", "link", ("red_meat", "chd"), "en")
        -> https://tools.epidetective.com/chronic/?lang=en#link=red_meat%7Cchd
      tool_link("cancer", "query", "Coffee, drinking", "es")
        -> https://tools.epidetective.com/cancer/?lang=es&q=Coffee%2C%20drinking

    The hash form stays valid when the tools gain path routes, so no site page
    depends on the Worker. Everything after '#' is percent-encoded (spaces,
    commas and the bar of a link id included): both tools decode the hash, and
    the HTML validator rejects a raw '|' in a URL.
    """
    if tool not in TOOL_ROOTS:
        raise ValueError("tool_link: unknown tool %r (want %s)" % (tool, sorted(TOOL_ROOTS)))
    if lang not in LANGS:
        raise ValueError("tool_link: unknown language %r (want %s)" % (lang, LANGS))
    url_ = "%s?lang=%s" % (TOOL_ROOTS[tool], lang)
    if kind is None:
        return url_
    if kind not in TOOL_KINDS[tool]:
        raise ValueError("tool_link: the %s tool has no %r view (want %s)"
                         % (tool, kind, list(TOOL_KINDS[tool])))
    if kind == "map":
        return url_ + "#map"
    if kind == "query":
        if not id or not isinstance(id, str):
            raise ValueError("tool_link: %s/query needs the search text" % tool)
        return url_ + "&q=" + quote(id, safe="")
    if kind == "link" and not isinstance(id, str):
        id = "|".join(id)
    if not id or not isinstance(id, str):
        raise ValueError("tool_link: %s/%s needs an id" % (tool, kind))
    frag = quote(id, safe="")
    return url_ + "#" + (frag if kind == "anchor" else "%s=%s" % (kind, frag))


