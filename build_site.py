def fig_parts(text):
    """'124 risk factors' -> ('124', 'risk factors'), as fig_row splits it."""
    m = re.match(r"^(\d[\d.,  ]*)\s*(.+)$", text)
    if not m:
        raise SystemExit("fig_parts: %r does not start with a count" % text)
    return m.groups()


