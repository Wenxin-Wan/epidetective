#!/usr/bin/env python3
"""Render the EpiDetective site once per language.

WordPress.com Simple strips JavaScript, so a live language switcher cannot run
there. Instead each language gets its own real page and the switcher is plain
links -- which also gives correct URLs and hreflang for search engines.

  design/index.html          en
  design/zh/index.html       zh
  design/fr/index.html       fr   ... etc

Run:  python3 build_site.py
"""
import html
import json
import os
import re
import shutil
from urllib.parse import quote

HERE = os.path.dirname(os.path.abspath(__file__))
I18N = os.path.join(HERE, "i18n")
TPL = os.path.join(HERE, "templates")
# Data the pages render, generated by local scripts and committed: the build
# (and the GitHub Action, which checks out design/ alone) reads only these.
#   data/work.json  <- scripts/build_work_data.py   (work.html)
WORK_JSON = os.path.join(HERE, "data", "work.json")

# en first: it is the source of truth for key parity
LANGS = ["en", "zh", "fr", "es", "ru"]
PAGES = {"index.html": "home", "explorer.html": "explorer", "about.html": "about",
         "games.html": "games", "reading.html": "reading",
         "how-we-check.html": "hwc", "work.html": "work"}
SITE_URL = "https://epidetective.com"
# og:image must be an absolute URL on a raster format; social scrapers ignore SVG
OG_IMAGE = SITE_URL + "/assets/og.png"
# og:locale wants a full locale, not the bare language code
OG_LOCALE = {"en": "en_GB", "zh": "zh_CN", "fr": "fr_FR", "es": "es_ES", "ru": "ru_RU"}
TOOL_URL = "https://tools.epidetective.com/cancer/"
# The second tool lives on tools.epidetective.com as well, so it is an absolute
# URL rather than a directory served from this repo.
TOOL2_URL = "https://tools.epidetective.com/chronic/"
# Every link into a tool carries the reader's language (?lang=, English too):
# both tools read it, skip their language gate and open in that language.
TOOL_ROOTS = {"cancer": TOOL_URL, "chronic": TOOL2_URL}
# The hash views each tool opens. "anchor" is a plain section id such as
# #methods or #how.
#   cancer   #exposure=<id>  #cancer=<id>  #map
#   chronic  #disease=<id>  #risk=<id>  #link=<risk>|<disease>  #map
TOOL_KINDS = {"cancer": ("exposure", "cancer", "map", "anchor"),
              "chronic": ("disease", "risk", "link", "map", "anchor")}
# The Code Against Cancer reference page is likewise a self-contained directory
# (bilingual EN/ZH inside), so it is linked with the same PREFIX join as TOOL2.
PREVENTION_PATH = "code-against-cancer/"
# The one genuine Note currently published, still living on the WordPress site.
# It must use the wordpress.com host: epidetective.com now points at this site on
# GitHub Pages, so the old epidetective.com/2026/... path no longer resolves.
NOTE1_URL = "https://epidetective.wordpress.com/2026/02/28/how-to-know-the-unknown/"
# The awareness games are self-contained static builds served from this repo,
# one directory each. All three are English-only, so every language links the
# same directories. GAME1 is a React bundle of
# github.com/Wenxin-Wan/sun-safety-adventure (Sol & the UV Shield Quest); GAME2
# is The Lung Detective, an investigation game about the causes of lung cancer;
# GAME3 is A Town of 1,000, a choices game about breast-cancer prevention.
GAME1_PATH = "games/sun-safety/"
GAME2_PATH = "games/lung-detective/"
GAME3_PATH = "games/town-of-1000/"

# Entries the site pages open in the tools, one placeholder each. Ids are written
# exactly as the tool's DATA has them; tool_link() adds ?lang= and encodes them.
TOOL_DEEP = {
    "TL_SOLAR": ("cancer", "exposure", "Solar radiation"),
    "TL_ALCOHOL": ("cancer", "exposure", "Alcoholic beverages"),
    "TL_ASBESTOS": ("cancer", "exposure", "Asbestos (all forms)"),
    "TL_TOBACCO": ("cancer", "exposure", "Tobacco smoking"),
    "TL_PROCESSED": ("cancer", "exposure", "Processed meat"),
    "TL_RF": ("cancer", "exposure", "Radiofrequency electromagnetic fields (glioma, acoustic neuroma)"),
    "TL_LUNG": ("cancer", "cancer", "Lung"),
    "TL_HOW": ("chronic", "anchor", "how"),
    "TL_REDMEAT_CHD": ("chronic", "link", ("red_meat", "chd")),
}

# Corrections go to one address; the subject stays English in every language so
# the reports can be filtered, and the body holds the four lines of the form.
REPORT_TO = "epidetective@gmail.com"
REPORT_SUBJECT = "EpiDetective correction"
REPORT_FIELDS = ("hwc_rep_i1", "hwc_rep_i2", "hwc_rep_i3", "hwc_rep_i4")
COLON = {"zh": "：", "fr": " : "}

# The labels the tools print, by IARC group and by chronic grade (i18n keys), and
# the class of the swatch that carries the tools' colour for each.
GROUP_KEY = {"1": "lbl_g1", "2A": "lbl_g2a", "2B": "lbl_g2b", "3": "lbl_g3"}
GRADE_KEY = {"Strong": "lbl_strong", "Moderate": "lbl_moderate", "Suggestive": "lbl_suggestive",
             "Weak": "lbl_weak", "Conflicting": "lbl_conflicting"}
# list separators inside a table cell
LIST_SEP = {"zh": "、"}

PLACEHOLDER = re.compile(r"\{\{([a-zA-Z0-9_.]+)\}\}")


def load(lang):
    with open(os.path.join(I18N, "%s.json" % lang), encoding="utf-8") as fh:
        return json.load(fh)


def url(lang, page, from_lang):
    """Relative URL to `page` in `lang`, seen from a page in `from_lang`.

    Links within the same language must stay bare filenames. Emitting
    "../zh/index.html" from inside zh/ resolves to the same file, but the
    browser treats it as a different URL and reloads the whole page, so
    in-page anchors stop working.
    """
    if lang == from_lang:
        return page
    prefix = "" if from_lang == "en" else "../"
    sub = "" if lang == "en" else lang + "/"
    return prefix + sub + page


def abs_url(lang, page):
    """Canonical absolute URL for `page` in `lang`.

    canonical, og:url, hreflang and the sitemap all need absolute URLs -- search
    engines treat a relative hreflang as a weaker hint, and social scrapers
    cannot resolve a relative og:url at all. index.html is dropped so the
    canonical form is the directory, matching what the server actually serves.
    """
    sub = "" if lang == "en" else lang + "/"
    leaf = "" if page == "index.html" else page
    return "%s/%s%s" % (SITE_URL, sub, leaf)


def tool_link(tool, kind, id, lang):
    """Absolute URL into one of the two tools, in the reader's language.

    tool  "cancer" or "chronic"
    kind  None for the tool's front door, else one of TOOL_KINDS[tool]
    id    the id exactly as the tool's DATA writes it ("Aspartame", "Tobacco
          smoking", "high_sbp"). For kind "link" either "risk|disease" or a
          (risk, disease) pair. Ignored for "map"; the section id for "anchor".
    lang  one of LANGS; always written, English included

    Examples:
      tool_link("cancer", "exposure", "Aspartame", "fr")
        -> https://tools.epidetective.com/cancer/?lang=fr#exposure=Aspartame
      tool_link("chronic", "link", ("red_meat", "chd"), "en")
        -> https://tools.epidetective.com/chronic/?lang=en#link=red_meat%7Cchd

    The hash form stays valid when the tools gain path routes, so no site page
    depends on the Worker. Everything after '#' is percent-encoded (spaces,
    commas and the bar of a link id included): both tools decode the hash, and
    the HTML validator rejects a raw '|' in a URL.
    """
    if tool not in TOOL_ROOTS:
        raise ValueError("tool_link: unknown tool %r (want %s)" % (tool, sorted(TOOL_ROOTS)))
    if lang not in LANGS:
        raise ValueError("tool_link: unknown language %r (want %s)" % (lang, LANGS))
    url_ = "%s?lang=%s" % (TOOL_ROOTS[tool], lang)
    if kind is None:
        return url_
    if kind not in TOOL_KINDS[tool]:
        raise ValueError("tool_link: the %s tool has no %r view (want %s)"
                         % (tool, kind, list(TOOL_KINDS[tool])))
    if kind == "map":
        return url_ + "#map"
    if kind == "link" and not isinstance(id, str):
        id = "|".join(id)
    if not id or not isinstance(id, str):
        raise ValueError("tool_link: %s/%s needs an id" % (tool, kind))
    frag = quote(id, safe="")
    return url_ + "#" + (frag if kind == "anchor" else "%s=%s" % (kind, frag))


def esc(text):
    """Escape a data value (a name taken from the tools' DATA) for HTML."""
    return html.escape(str(text), quote=True)


def group_code(d, group):
    """'Group 2A', '2A 类', 'groupe 2A' ... from the language's lbl_grp pattern."""
    return d["lbl_grp"].replace("{g}", group)


def vol_text(d, volume, year):
    """'Vol. 100C, 2009' or 'Suppl. 7, 1987' in the page's language."""
    m = re.match(r"^Sup\s*(\S+)$", volume)
    pattern = d["work_sup"] if m else d["work_vol"]
    return pattern.replace("{n}", m.group(1) if m else volume).replace("{year}", str(year))


def mailto_report(d, lang):
    """mailto: URL for a correction, its body the four lines of the form.

    RFC 6068 wants CRLF line breaks in a mailto body. The result goes into an
    href attribute, so its one '&' is written as &amp;."""
    lines = [html.unescape(re.sub(r"<[^>]+>", "", d[key])).strip() + COLON.get(lang, ": ")
             for key in REPORT_FIELDS]
    body = "\r\n".join(lines) + "\r\n"
    return "mailto:%s?subject=%s&amp;body=%s" % (REPORT_TO, quote(REPORT_SUBJECT),
                                                 quote(body, safe=""))


def swatch(cls):
    """The small square in the tools' colour for a group (g1 ...) or a grade
    (strong ...); site.css .sw.<cls>. The label next to it carries the meaning."""
    return '<span class="sw %s" aria-hidden="true"></span>' % cls


def render_work(work, d, lang):
    """work.html: the sector index and one table per sector, from data/work.json."""
    sep = LIST_SEP.get(lang, ", ")
    toc, sections = [], []
    for sector in work["sectors"]:
        sid, n = sector["id"], len(sector["agents"])
        name = d["work_sec_" + sid]
        toc.append('<li><a href="#%s">%s <span class="n">%d</span></a></li>' % (sid, name, n))
        rows = []
        for a in sector["agents"]:
            g = a["group"]
            counts = []
            for kind in ("established", "suspected"):
                names = sep.join(esc(c["name"][lang]) for c in a[kind])
                counts.append('<td><span class="n">%d</span>%s</td>'
                              % (len(a[kind]), " " + names if names else ""))
            rows.append('<tr><th scope="row"><a href="%s">%s</a></th>'
                        '<td>%s%s <span class="gc">%s</span></td>%s<td class="ev">%s</td></tr>'
                        % (esc(tool_link("cancer", "exposure", a["id"], lang)), esc(a["name"][lang]),
                           swatch(GROUP_KEY[g].replace("lbl_", "")), d[GROUP_KEY[g]], group_code(d, g),
                           "".join(counts), vol_text(d, a["volume"], a["year"])))
        sections.append(
            '<section class="work-sec" id="%s">\n<h2 id="h-%s">%s <span class="n">%d</span></h2>\n'
            '<div class="tbl-wrap" role="region" tabindex="0" aria-labelledby="h-%s">\n'
            '<table class="work-table">\n<colgroup><col class="c-agent"><col class="c-label">'
            '<col class="c-est"><col class="c-sus"><col class="c-ev"></colgroup>\n'
            '<thead><tr><th scope="col">%s</th><th scope="col">%s</th><th scope="col">%s</th>'
            '<th scope="col">%s</th><th scope="col">%s</th></tr></thead>\n<tbody>\n%s\n</tbody>\n'
            '</table>\n</div>\n</section>'
            % (sid, sid, name, n, sid, d["work_th_agent"], d["work_th_label"], d["work_th_est"],
               d["work_th_sus"], d["work_th_eval"], "\n".join(rows)))
    return '<ul>%s</ul>' % "".join(toc), "\n\n".join(sections)


def render_rec9(work, d, lang):
    """European Code recommendation 9, verbatim from the Code page's REGIONS.

    Where IARC publishes no edition in the page's language (zh, ru) the text is
    EpiDetective's rendering, and the note above it says so, as the Code page does."""
    r = work["ecac5_rec9"]
    official = lang in r["official_langs"]
    url_ = r["official_by_lang"].get(lang, r["official"])
    j = r["justification"]
    note = ('<p class="ecac-note">%s</p>' % d["work_ecac_official"] if official
            else '<p class="ecac-note summary">%s</p>' % d["work_ecac_rendering"])
    return (note
            + '\n<blockquote class="ecac" cite="%s">\n<p class="ecac-t"><span class="n">%d</span> %s</p>'
              '\n<p>%s</p>\n</blockquote>' % (esc(url_), r["number"], esc(r["title"][lang]),
                                              esc(r["text"][lang]))
            + '\n<p class="ecac-src"><a href="%s" rel="noopener">%s</a></p>' % (esc(url_), d["work_ecac_link"])
            + '\n<p class="ecac-why"><span class="k">%s</span> <a href="https://doi.org/%s">%s</a>. '
              '<i>%s</i> %s;%s(%s):%s. doi:%s</p>'
              % (d["work_ecac_why"], esc(j["doi"]), esc(j["title"]), esc(j["journal"]), j["year"],
                 esc(j["volume"]), esc(j["issue"]), esc(j["pages"]).replace("-", "–"),
                 esc(j["doi"])))


def render_work_chronic(work, d, lang):
    """work.html, Beyond cancer: the chronic tool's Occupational risk factors,
    each with its counted links and their grades."""
    items = []
    for r in work["chronic"]:
        links = "".join(
            '<li><a href="%s">%s</a> <span class="gr">%s%s</span></li>'
            % (esc(tool_link("chronic", "link", (r["id"], l["disease"]), lang)), esc(l["name"][lang]),
               swatch(GRADE_KEY[l["grade"]].replace("lbl_", "")), d[GRADE_KEY[l["grade"]]])
            for l in r["links"])
        rel = ('<p class="rel">%s</p>' % d["work_beyond_rel"].replace("{n}", str(r["n_related"]))
               if r["n_related"] else "")
        items.append('<li><a class="bn" href="%s">%s</a><div><ul class="bl">%s</ul>%s</div></li>'
                     % (esc(tool_link("chronic", "risk", r["id"], lang)), esc(r["name"][lang]),
                        links, rel))
    return '<ul class="beyond">\n%s\n</ul>' % "\n".join(items)


def write_sitemap():
    """One <url> per page per language, each listing every language as an
    alternate. Search engines want the alternates repeated inside every entry,
    not only on the page that happens to be canonical."""
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"'
           ' xmlns:xhtml="http://www.w3.org/1999/xhtml">']
    for page in PAGES:
        for lang in LANGS:
            out.append("  <url>")
            out.append("    <loc>%s</loc>" % abs_url(lang, page))
            for other in LANGS:
                out.append('    <xhtml:link rel="alternate" hreflang="%s" href="%s"/>'
                           % (other, abs_url(other, page)))
            out.append('    <xhtml:link rel="alternate" hreflang="x-default" href="%s"/>'
                       % abs_url("en", page))
            out.append("  </url>")
    # The two tools are behind the tools.epidetective.com login gate and are no
    # longer indexable, so neither gets a sitemap entry. The Code Against Cancer
    # page is self-contained and bilingual and stays public.
    out.append("  <url>")
    out.append("    <loc>%s/%s</loc>" % (SITE_URL, PREVENTION_PATH))
    out.append("  </url>")
    # The developer timeline and the three games are public standalone pages.
    for leaf in ("timeline/", GAME1_PATH, GAME2_PATH, GAME3_PATH):
        out.append("  <url>")
        out.append("    <loc>%s/%s</loc>" % (SITE_URL, leaf))
        out.append("  </url>")
    out.append("</urlset>")
    with open(os.path.join(HERE, "sitemap.xml"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")


def write_robots():
    lines = ["User-agent: *", "Allow: /", "", "Sitemap: %s/sitemap.xml" % SITE_URL]
    with open(os.path.join(HERE, "robots.txt"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


def main():
    data = {l: load(l) for l in LANGS}

    # --- key parity: a missing key must fail the build, not silently ship English
    base = set(data["en"])
    problems = []
    for l in LANGS[1:]:
        missing = base - set(data[l])
        extra = set(data[l]) - base
        if missing:
            problems.append("%s missing %d: %s" % (l, len(missing), sorted(missing)[:6]))
        if extra:
            problems.append("%s has %d unknown: %s" % (l, len(extra), sorted(extra)[:6]))
        empty = [k for k, v in data[l].items() if not str(v).strip()]
        if empty:
            problems.append("%s empty values: %s" % (l, empty[:6]))
    if problems:
        raise SystemExit("Translation key problems:\n  " + "\n  ".join(problems))

    templates = {}
    for page in PAGES:
        with open(os.path.join(TPL, page), encoding="utf-8") as fh:
            templates[page] = fh.read()

    # work.html renders the committed output of scripts/build_work_data.py
    with open(WORK_JSON, encoding="utf-8") as fh:
        work = json.load(fh)

    written = []
    for lang in LANGS:
        d = data[lang]
        outdir = HERE if lang == "en" else os.path.join(HERE, lang)
        os.makedirs(outdir, exist_ok=True)

        work_toc, work_sectors = render_work(work, d, lang)
        shared = {
            "URL_HWC": url(lang, "how-we-check.html", lang),
            "URL_WORK": url(lang, "work.html", lang),
            "MAILTO_REPORT": mailto_report(d, lang),
            "WORK_TOC": work_toc,
            "WORK_SECTORS": work_sectors,
            "WORK_REC9": render_rec9(work, d, lang),
            "WORK_CHRONIC": render_work_chronic(work, d, lang),
        }
        for key, (tool, kind, id_) in TOOL_DEEP.items():
            shared[key] = tool_link(tool, kind, id_, lang)
        for g in GROUP_KEY:
            shared["GRP_" + g] = group_code(d, g)

        for page in PAGES:
            # language switcher: plain links, no JavaScript required. Built per
            # page so switching language keeps you on the same page rather than
            # dumping you back to the home page.
            switch = []
            for other in LANGS:
                label = data[other]["lang_name"]
                if other == lang:
                    switch.append('<span class="lang-cur" aria-current="true">%s</span>' % label)
                else:
                    switch.append('<a href="%s" hreflang="%s">%s</a>'
                                  % (url(other, page, lang), other, label))
            switch_html = "".join(switch)

            # hreflang alternates for this page across every language
            alts = ['<link rel="alternate" hreflang="%s" href="%s">'
                    % (o, abs_url(o, page)) for o in LANGS]
            alts.append('<link rel="alternate" hreflang="x-default" href="%s">'
                        % abs_url("en", page))

            ctx = dict(d)
            ctx["LANG"] = lang
            ctx["DIR"] = d.get("lang_dir", "ltr")
            ctx["PREFIX"] = "" if lang == "en" else "../"
            ctx["URL_HOME"] = url(lang, "index.html", lang)
            ctx["URL_EXPLORER"] = url(lang, "explorer.html", lang)
            ctx["URL_ABOUT"] = url(lang, "about.html", lang)
            ctx["URL_GAMES"] = url(lang, "games.html", lang)
            ctx["URL_READING"] = url(lang, "reading.html", lang)
            ctx["URL_GAME1"] = ctx["PREFIX"] + GAME1_PATH
            ctx["URL_GAME2"] = ctx["PREFIX"] + GAME2_PATH
            ctx["URL_GAME3"] = ctx["PREFIX"] + GAME3_PATH
            ctx["URL_TOOL"] = tool_link("cancer", None, None, lang)
            ctx["URL_TOOL2"] = tool_link("chronic", None, None, lang)
            # the Code page localises itself client-side; hand it the language
            ctx["URL_PREVENTION"] = (ctx["PREFIX"] + PREVENTION_PATH
                                     + ("" if lang == "en" else "?lang=" + lang))
            # the timeline speaks en/zh; only zh gets the handoff
            ctx["URL_TIMELINE"] = (ctx["PREFIX"] + "timeline/"
                                   + ("?lang=zh" if lang == "zh" else ""))
            ctx["URL_NOTE1"] = NOTE1_URL
            ctx["CANONICAL"] = abs_url(lang, page)
            ctx["OG_IMAGE"] = OG_IMAGE
            ctx["OG_LOCALE"] = OG_LOCALE[lang]
            ctx["LANGSWITCH"] = switch_html
            ctx["HREFLANG"] = "\n".join(alts)
            ctx.update(shared)

            missing = []

            def sub(m):
                k = m.group(1)
                if k not in ctx:
                    missing.append(k)
                    return m.group(0)
                return str(ctx[k])

            html = PLACEHOLDER.sub(sub, templates[page])
            # dev-notes stay in the templates; the shipped page carries none
            html = re.sub(r"[ \t]*<!--(?!\[).*?-->\n?", "", html, flags=re.S)
            if missing:
                raise SystemExit("%s/%s: unresolved placeholders %s"
                                 % (lang, page, sorted(set(missing))))

            path = os.path.join(outdir, page)
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(html)
            written.append(os.path.relpath(path, HERE))

    write_sitemap()
    write_robots()

    print("Built %d pages across %d languages:" % (len(written), len(LANGS)))
    for w in written:
        print("   ", w)
    print("\nKey count: %d strings x %d languages" % (len(base), len(LANGS)))

    # The About citation (cite_p) and the How we check versions (hwc_ver_c) name
    # the cancer tool's build date by a literal {cancerBuilt}; the publisher fills
    # it in (with the date of the tool's DATA.meta.built) before the pages go
    # live. Say so while any is open.
    pending = sorted({"%s:%s" % (l, k) for l in LANGS for k, v in data[l].items()
                      if "{cancerBuilt}" in str(v)})
    if pending:
        print("NOTE: the placeholder {cancerBuilt} is still open in %s: replace it"
              " with the cancer tool's build date before publishing." % ", ".join(pending))


if __name__ == "__main__":
    main()
